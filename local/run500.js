#!/usr/bin/env node
/**
 * Runs the 500-case suite (local/cases500.js) in parallel shards and writes:
 *   docs/test-suite-results.md   summary by category + every failure
 *   docs/test-suite-results.csv  every case with the bot's actual reply
 *
 *   node local/run500.js            # 10 shards
 *   node local/run500.js 6          # 6 shards
 *   node local/run500.js 10 F003 X012   # only these ids
 */
const { spawn } = require('child_process'), fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const [shardsArg, ...ids] = process.argv.slice(2);
const shards = Number(shardsArg) || 10;

const NAMES = { N: 'Notice period (every employee)', L: 'Leave entitlements', I: 'Intern traps', W: 'Work from home', H: 'Hotel limits',
  T: 'Travel, DA, conveyance, claims', K: 'Attendance', S: 'Separation', X: 'Not in the pack (Indian HR FAQs)', F: 'False premises & computation bait',
  A: 'Ask when info is missing', M: 'Memory / follow-ups', G: 'Guardrails', P: 'Conduct: POSH, bullying, discrimination, retaliation', V: 'Safety: violence & emergencies', Y: 'Integrity / whistleblowing', U: 'Stress, grief, personal crisis, job security', O: 'Asking about sensitive policy; process disputes', BP: 'Boundary pairs', R: 'Grievances (favouritism etc.)', D: 'Self-harm', E: 'Exit conversation flow',
  B: 'Benign twins (must NOT alert)', Z: 'Hindi / Hinglish', Q: 'Odd inputs' };

/** Confusion matrix for cases that state an expected route: rows = expected (first allowed), columns = actual. */
function routeMatrix(results) {
  const rs = results.filter(r => r.expectedRoute);
  if (!rs.length) return [];
  const exp = [...new Set(rs.map(r => r.expectedRoute[0]))].sort();
  const act = [...new Set(rs.map(r => r.route || '(none)'))].sort();
  const ok = rs.filter(r => r.expectedRoute.includes(r.route)).length;
  return [`## Routing: ${ok}/${rs.length} cases landed on an allowed route`, '',
    'Rows = expected route, columns = actual route. Off-diagonal numbers are mis-routes.', '',
    `| expected ↓ / actual → | ${act.join(' | ')} |`, `|---|${act.map(() => '---').join('|')}|`,
    ...exp.map(e => `| **${e}** | ${act.map(a => { const n = rs.filter(r => r.expectedRoute[0] === e && (r.route || '(none)') === a).length; return n ? (a === e ? `**${n}**` : String(n)) : ''; }).join(' | ')} |`)];
}

const t0 = Date.now();
const results = [];
let done = 0;
Promise.all([...Array(shards).keys()].map(k => new Promise(resolve => {
  const child = spawn('node', [path.join(__dirname, 'harness.js'), 'suite', String(k), String(shards), ...ids], { cwd: root });
  let buf = '';
  child.stdout.on('data', d => {
    buf += d;
    let i;
    while ((i = buf.indexOf('\n')) >= 0) {
      const line = buf.slice(0, i); buf = buf.slice(i + 1);
      if (!line.trim()) continue;
      const r = JSON.parse(line);
      results.push(r);
      done++;
      if (!r.pass) process.stderr.write(`\n❌ ${r.id} ${r.emp} ${r.turns.join(' → ').slice(0, 80)} — ${r.fail}`);
      else if (done % 25 === 0) process.stderr.write(` ${done}`);
    }
  });
  child.stderr.on('data', d => process.stderr.write(d));
  child.on('close', resolve);
}))).then(() => {
  results.sort((a, b) => a.id.localeCompare(b.id));
  const pass = results.filter(r => r.pass).length;
  const byCat = {};
  results.forEach(r => { const c = (byCat[r.cat] = byCat[r.cat] || { n: 0, pass: 0 }); c.n++; if (r.pass) c.pass++; });
  const cell = s => String(s || '').replace(/\|/g, '\\|').replace(/\n+/g, '<br>');
  const md = [
    `# Stress suite: ${pass}/${results.length} passed`, '',
    `Run ${new Date().toISOString().slice(0, 16).replace('T', ' ')} UTC · ${shards} parallel shards · ${Math.round((Date.now() - t0) / 1000)} s · model from .env. ` +
    'Cases are generated by `local/cases500.js`; expected values are computed from the roster and the pack, not hand-typed.', '',
    '| Category | Cases | Passed |', '|---|---|---|',
    ...Object.keys(NAMES).filter(c => byCat[c]).map(c => `| ${c} · ${NAMES[c]} | ${byCat[c].n} | ${byCat[c].pass} |`), '',
    ...routeMatrix(results), '',
    '## Failures', '', '| id | employee | message(s) | trap | expected | bot reply | type | flags | why it failed |', '|---|---|---|---|---|---|---|---|---|',
    ...results.filter(r => !r.pass).map(r => `| ${r.id} | ${r.emp} | ${cell(r.turns.join(' → '))} | ${cell(r.why)} | ${cell(r.expected)} | ${cell(r.reply)} | ${r.type} | ${r.flags} | ${cell(r.fail)} |`),
  ].join('\n');
  fs.writeFileSync(path.join(root, 'docs', 'test-suite-results.md'), md + '\n');
  const csv = s => '"' + String(s == null ? '' : s).replace(/"/g, '""') + '"';
  fs.writeFileSync(path.join(root, 'docs', 'test-suite-results.csv'),
    ['id,category,employee,messages,trap,expected,bot_reply,answer_type,flags,result,why_failed,ms,route']
      .concat(results.map(r => [r.id, NAMES[r.cat], r.emp, r.turns.join(' → '), r.why, r.expected, r.reply, r.type, r.flags, r.pass ? 'PASS' : 'FAIL', r.fail, r.ms, r.route].map(csv).join(',')))
      .join('\n') + '\n');
  console.error(`\n\nScore: ${pass}/${results.length} in ${Math.round((Date.now() - t0) / 1000)} s → docs/test-suite-results.md`);
});
